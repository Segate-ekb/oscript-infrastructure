-- Выгрузка данных пакетов из базы старого хаба (opm-hub) — вход разового переноса в OpenHub.
-- Запускается в базе сервиса opm_hub_db, пишет CSV в стандартный вывод. Ничего не меняет.
--
-- Таблицы старого хаба создавала библиотека entity запросом CREATE TABLE без кавычек:
-- ASCII-буквы PostgreSQL привёл к нижнему регистру, кириллицу оставил как есть. Поэтому
-- имена здесь в кавычках ровно в том виде, в каком лежат в каталоге.

COPY (
    SELECT lower(p."Код")                        AS имя_пакета,
           v."Номер"                             AS версия,
           v."ДатаСоздания"                      AS версия_создана,
           v."ДатаОбновления"                    AS версия_обновлена,
           coalesce(v."ТестоваяСборка", false)   AS тестовая_сборка,
           p."ДатаСоздания"                      AS пакет_создан,
           p."ДатаОбновления"                    AS пакет_обновлён,
           coalesce(p."Описание", '')            AS описание,
           coalesce(p."КлючевыеСлова", '')       AS ключевые_слова,
           coalesce(p."СсылкаНаПроект", '')      AS ссылка_на_проект,
           coalesce(a."Имя", '')                 AS автор,
           coalesce(a."ЭлектроннаяПочта", '')    AS автор_почта,
           coalesce(a."УчетнаяЗапись", '')       AS автор_учётка
    FROM "ВерсииПакетов" v
    JOIN "Пакеты" p ON p."Код" = v."Пакет"
    LEFT JOIN "Авторы" a ON a."Код" = p."Автор"
    ORDER BY 1, 2
) TO STDOUT WITH (FORMAT csv, HEADER true);
